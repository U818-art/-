/** スプレッドを引く。重複なし・正逆は各カード独立に 1/2。 */
export function drawSpread(spreadKey) {
  const spread = SPREADS[spreadKey]
  const used = new Set()
  const cards = spread.positions.map((pos) => {
    let idx
    do {
      idx = randInt(DECK.length)
    } while (used.has(idx))
    used.add(idx)
    const reversed = randInt(2) === 1
    return { position: pos, card: DECK[idx], reversed }
  })
  return { spreadKey, spreadName: spread.name, cards, drawnAt: new Date() }
}
